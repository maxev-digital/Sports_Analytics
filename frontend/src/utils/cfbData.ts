export function getCfbRating(teamName: string): CfbRating | null {
  // Try exact match first
  if (teamName in CFB_POWER_RATINGS) return CFB_POWER_RATINGS[teamName];
  // Try matching on last word (mascot)
  const mascot = teamName.split(' ').pop() || '';
  for (const [key, val] of Object.entries(CFB_POWER_RATINGS)) {
    if (key.includes(mascot) || teamName.includes(key.split(' ')[0])) return val;
  }
  return null;
}
